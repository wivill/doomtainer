#!/bin/bash

# 1. Get user IDs
USER_UID=$(id -u)
USER_GID=$(id -g)

# 2. Locate the PulseAudio/Pipewire Cookie
# It is usually in ~/.config/pulse/cookie, but sometimes it varies.
if [ -f "$HOME/.config/pulse/cookie" ]; then
    PULSE_COOKIE_PATH="$HOME/.config/pulse/cookie"
elif [ -f "$HOME/.pulse-cookie" ]; then
    PULSE_COOKIE_PATH="$HOME/.pulse-cookie"
else
    # If it does not exist, we generate a dummy so that docker does not fail when mounting,
    # although the audio might not work without it if security is strict.
    echo "Warning: Audio cookie not found."
    touch /tmp/dummy_pulse_cookie
    PULSE_COOKIE_PATH="/tmp/dummy_pulse_cookie"
fi

# 3. Bind-mount sources must exist and be yours: Docker creates missing ones
# as root. Older versions ran the container as root, so check for leftovers
# before creating anything.
if [ -n "$(find config original_wads map_wads mods ! -user "$USER_UID" -print -quit 2>/dev/null)" ]; then
    echo "Error: some files under config/ or the WAD/mod folders aren't owned by you" >&2
    echo "(left over from when the container ran as root). Fix once with:" >&2
    echo "    sudo chown -R $USER_UID:$USER_GID config original_wads map_wads mods" >&2
    exit 1
fi
mkdir -p original_wads map_wads mods config/savegames

# 4. Give the container the host's GPU/sound device groups (device nodes keep
# host GIDs). Generated per host because group IDs differ between distros, a
# group may not exist at all, and compose rejects duplicate entries.
DEVICE_GIDS="$(for group in video render audio; do getent group "$group" | cut -d: -f3; done | sort -u)"
{
    echo "# Generated by run.sh; host-specific, do not commit."
    echo "services:"
    echo "  gzdoom:"
    if [ -z "$DEVICE_GIDS" ]; then
        echo "    group_add: []"
    else
        echo "    group_add:"
        for gid in $DEVICE_GIDS; do
            echo "      - \"$gid\""
        done
    fi
} > docker-compose.override.yml

# 5. Create dynamic .env file
{
    echo "UID=$USER_UID"
    echo "GID=$USER_GID"
    echo "XDG_RUNTIME_DIR=$XDG_RUNTIME_DIR"
    echo "WAYLAND_DISPLAY=$WAYLAND_DISPLAY"
    echo "DISPLAY=$DISPLAY"
    echo "PULSE_COOKIE_HOST=$PULSE_COOKIE_PATH"
} > .env

# 6. Screen permissions (X11 fallback), scoped to your own user now that the
# container no longer runs as root.
xhost +SI:localuser:"$(id -un)" >/dev/null 2>&1

# 7. Execute
docker compose up --build