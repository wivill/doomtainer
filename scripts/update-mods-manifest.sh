#!/bin/bash
# Regenerate mods.sha256 from the files the docker-compose.yml command block
# loads. Run it after changing the mod list or updating a mod, commit the
# result, and copy the new files to every machine: the launchers refuse to
# start when a machine's files don't match, since its saves wouldn't load
# elsewhere.

set -euo pipefail

cd "$(dirname "$0")/.."
# shellcheck source=lib/common.sh
. lib/common.sh

{
    echo "# Generated by scripts/update-mods-manifest.sh; checked by the launchers."
    while IFS= read -r file; do
        [ -e "$file" ] || die "missing $file"
        printf '%s  %s\n' "$(sha256_of "$file")" "$file"
    done < <(game_files)
} > "$MODS_MANIFEST"
cat "$MODS_MANIFEST"
